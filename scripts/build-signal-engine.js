// Copies the trading analysis (src/pages/forex-trader/engine.ts) into a plain
// JavaScript file the server-side signal watcher can load: api/_lib/engine.js.
//
// WHY: engine.ts is the single source of truth for the strategy logic. The chart
// and the 24/7 watcher must produce the SAME signals, so we never rewrite the logic;
// we only convert TypeScript to JavaScript. This runs automatically before every
// build ("prebuild" in package.json). You can also run it by hand: node scripts/build-signal-engine.js
//
// If anything goes wrong it only prints a warning and keeps the committed copy,
// so it can never break the website build.
const fs = require('fs');
const path = require('path');

// engine.ts is the H1 strategy logic; mtf.ts is the M15 + M5 multi-timeframe analysis (it uses engine.ts); ict.ts is the ICT strategy (it uses mtf.ts).
const FILES = ['engine', 'mtf', 'ict', 'pdh', 'grab'];

try {
    const ts = require('typescript');
    for (const name of FILES) {
        const SRC = path.join(__dirname, `../src/pages/forex-trader/${name}.ts`);
        const OUT = path.join(__dirname, `../api/_lib/${name}.js`);
        const source = fs.readFileSync(SRC, 'utf8');
        const result = ts.transpileModule(source, {
            compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
        });
        const header =
            `// AUTO-GENERATED from src/pages/forex-trader/${name}.ts by scripts/build-signal-engine.js.\n` +
            `// DO NOT EDIT THIS FILE BY HAND: edit ${name}.ts instead and rebuild.\n`;
        const next = header + result.outputText;
        const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
        if (next !== prev) {
            fs.writeFileSync(OUT, next);
            console.log(`build-signal-engine: api/_lib/${name}.js updated`);
        } else {
            console.log(`build-signal-engine: api/_lib/${name}.js already up to date`);
        }
    }
} catch (err) {
    console.warn('build-signal-engine: WARNING, could not regenerate the api/_lib engine files:', err && err.message);
}
